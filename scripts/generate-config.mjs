import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import nextEnv from '@next/env';

const projectDir = process.cwd();
const mode = process.argv[2] === 'production' ? 'production' : 'development';
process.env.NODE_ENV ||= mode;
nextEnv.loadEnvConfig(projectDir, mode === 'development');

const trimTrailingSlashes = (value) => value.replace(/\/+$/, '');
const baseUrl = trimTrailingSlashes(process.env.BASE_URL || 'http://localhost:9503');
const calendarApiUrl = trimTrailingSlashes(
  process.env.CALENDAR_API_URL || process.env.CALENDAR_URL || 'http://localhost:8443',
);
const calendarUrl = trimTrailingSlashes(
  process.env.CALENDAR_URL || process.env.CALENDAR_API_URL || 'http://localhost:8443',
);
const config = {
  baseUrl,
  apiUrl: trimTrailingSlashes(process.env.API_URL || `${baseUrl}/api/v1/imap`),
  calendarApiUrl,
  calendarUrl,
  apiVersion: process.env.API_VERSION || 'v1',
  appName: process.env.APP_NAME || 'AirSend',
  appVersion: process.env.APP_VERSION || '1.0.0',
  nodeEnv: process.env.NODE_ENV || 'development',
  defaultTheme: 'dark',
  enableWebPush: process.env.ENABLE_WEBPUSH !== 'false',
};
const output = `// Generated by scripts/generate-config.mjs. Do not edit by hand.\nwindow.__RUNTIME_CONFIG__ = ${JSON.stringify(config, null, 2)};\n`;

await writeFile(path.join(projectDir, 'public', 'config.js'), output);
console.log('Generated public/config.js');
